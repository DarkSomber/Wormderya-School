/**
 * Builds audio/audioManifest.js from whatever is in assets/audio/.
 *
 *   assets/audio/sfx/  click.wav, correct.wav, ...            -> SFX.click, ...
 *   assets/audio/va/   eating_1.mp3, goodbye_3.mp3, ...       -> VA.eating_1, ...
 *   assets/audio/bgm/  anything with "menu" in the name       -> BGM.menu
 *                      anything with "level"/"game"/"play"    -> BGM.level
 *
 * Metro needs literal require() paths, so this script writes them for us.
 * Run it after adding or renaming audio:   npm run audio
 * (npm start / android / ios / web run it automatically.)
 * Missing files become `null` and the game simply stays silent for them.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio');
const OUT_FILE = path.join(ROOT, 'audio', 'audioManifest.js');

// Preference order if the same name exists in two formats.
const EXTS = ['.wav', '.mp3', '.ogg', '.m4a', '.aac', '.flac'];

const EXPECTED = {
  sfx: [
    'click', 'correct', 'lose', 'new_record', 'ratty_buy', 'ratty_chirp',
    'ratty_ignore', 'ratty_shop_appear', 'serve_letters', 'serve_word',
    'trophy', 'win', 'wrong',
  ],
  va: ['eating', 'ehem', 'goodbye', 'greetings', 'haha', 'satisfied', 'shocked', 'sighing']
    .flatMap((type) => [1, 2, 3].map((n) => `${type}_${n}`)),
  bgm: ['menu', 'level'],
};

// How a BGM file name maps to a track (checked in this order).
const BGM_MATCH = {
  menu: /menu|title|home|main/i,
  level: /level|game|play|stage|battle|shift/i,
};

for (const dir of Object.keys(EXPECTED)) {
  fs.mkdirSync(path.join(AUDIO_DIR, dir), { recursive: true });
}

/** { baseName: 'file.ext' } for one folder. */
function scan(dir) {
  const found = {};
  const folder = path.join(AUDIO_DIR, dir);
  for (const file of fs.readdirSync(folder).sort()) {
    const ext = path.extname(file).toLowerCase();
    if (file.startsWith('.') || !EXTS.includes(ext)) continue;
    const base = path.basename(file, path.extname(file));
    const prev = found[base];
    if (prev) {
      const keepPrev = EXTS.indexOf(path.extname(prev).toLowerCase()) <= EXTS.indexOf(ext);
      console.warn(`  ! ${dir}/${base}: two formats found, using ${keepPrev ? prev : file}`);
      if (keepPrev) continue;
    }
    found[base] = file;
  }
  return found;
}

const sfx = scan('sfx');
const va = scan('va');

// BGM: pick files by name, then fall back to the one leftover file.
const bgmFiles = scan('bgm');
const bgm = {};
const unassigned = new Set(Object.keys(bgmFiles));
for (const key of EXPECTED.bgm) {
  const hit = [...unassigned].find((base) => BGM_MATCH[key].test(base));
  if (hit) {
    bgm[key] = bgmFiles[hit];
    unassigned.delete(hit);
  }
}
for (const key of EXPECTED.bgm) {
  if (!bgm[key] && unassigned.size === 1) {
    const [only] = unassigned;
    bgm[key] = bgmFiles[only];
    unassigned.delete(only);
    console.warn(`  ! bgm: "${only}" didn't say menu/level; using it as "${key}"`);
  }
}

const line = (dir, key, file) =>
  file
    ? `  ${JSON.stringify(key)}: require('../assets/audio/${dir}/${file}'),`
    : `  ${JSON.stringify(key)}: null, // missing`;

function section(name, dir, files, expected) {
  const keys = [...expected, ...Object.keys(files).filter((k) => !expected.includes(k))];
  const body = keys.map((k) => line(dir, k, files[k])).join('\n');
  return `export const ${name} = {\n${body}\n};\n`;
}

const bgmBody = EXPECTED.bgm.map((k) => line('bgm', k, bgm[k])).join('\n');

const output = `// AUTO-GENERATED by scripts/generate-audio-manifest.js. Do not edit by hand.
// Add or rename files in assets/audio/, then run: npm run audio

${section('SFX', 'sfx', sfx, EXPECTED.sfx)}
${section('VA', 'va', va, EXPECTED.va)}
export const BGM = {
${bgmBody}
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output);

const missing = {
  sfx: EXPECTED.sfx.filter((k) => !sfx[k]),
  va: EXPECTED.va.filter((k) => !va[k]),
  bgm: EXPECTED.bgm.filter((k) => !bgm[k]),
};
console.log(
  `audio manifest: sfx ${EXPECTED.sfx.length - missing.sfx.length}/${EXPECTED.sfx.length}, ` +
  `va ${EXPECTED.va.length - missing.va.length}/${EXPECTED.va.length}, ` +
  `bgm ${EXPECTED.bgm.length - missing.bgm.length}/${EXPECTED.bgm.length}`
);
for (const [dir, list] of Object.entries(missing)) {
  if (list.length) console.warn(`  missing in ${dir}/: ${list.join(', ')}`);
}
for (const key of EXPECTED.bgm) {
  if (bgm[key]) console.log(`  bgm.${key} <- ${bgm[key]}`);
}
